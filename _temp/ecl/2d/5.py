def plot_graph():
    selected_temps = [float(listbox_temps.get(i)) for i in listbox_temps.curselection()]
    selected_steps = [float(listbox_steps.get(i)) for i in listbox_steps.curselection()]
    selected_compounds = [listbox_compounds.get(i) for i in listbox_compounds.curselection()]
    
    if not selected_temps or not selected_steps or not selected_compounds:
        messagebox.showwarning("Ошибка", "Выберите хотя бы одну температуру, один шаг и одну ЖК!")
        return

    filtered_df = df[(df["Init_Temp"].isin(selected_temps)) & 
                     (df["Temp_Step"].isin(selected_steps)) & 
                     (df["Compound"].isin(selected_compounds))]
    
    plot_type = var_plot_type.get()
    x_axis = var_x_axis.get()
    do_regression = var_regression.get()
    degree = var_degree.get()
    
    sns.set_theme(style="whitegrid")
    
    if x_axis == "Temp_Step":
        x_col, hue_col = "Temp_Step", "Init_Temp"
        x_label, hue_label = "Шаг температуры", "Нач. температура (°C)"
    else:
        x_col, hue_col = "Init_Temp", "Temp_Step"
        x_label, hue_label = "Начальная температура (°C)", "Шаг температуры"

    # --- ЛИНЕЙНЫЙ ГРАФИК С РЕГРЕССИЕЙ ---
    if plot_type == "Line":
        plt.figure(figsize=(12, 7))
        stats_list = []
        
        # Перебираем выбранные ЖК
        for comp in selected_compounds:
            comp_df = filtered_df[filtered_df["Compound"] == comp]
            
            # Перебираем выбранные температуры/шаги для текущей ЖК
            for val in sorted(comp_df[hue_col].unique()):
                subset = comp_df[comp_df[hue_col] == val]
                x_data = subset[x_col].values
                y_data = subset['ECL'].values
                
                # Формируем название кривой для легенды и таблицы
                curve_label = f"{comp} ({val})"
                
                if do_regression and len(x_data) > degree:
                    coeffs = np.polyfit(x_data, y_data, degree)
                    y_pred = np.polyval(coeffs, x_data)
                    
                    ss_res = np.sum((y_data - y_pred) ** 2)
                    ss_tot = np.sum((y_data - np.mean(y_data)) ** 2)
                    r_squared = 1 - (ss_res / ss_tot) if ss_tot != 0 else 1
                    rmse = np.sqrt(ss_res / len(y_data))
                    
                    p = plt.plot(x_data, y_data, marker='o', linestyle='', label=f'{curve_label} (данные)')
                    color = p[0].get_color()
                    
                    x_smooth = np.linspace(x_data.min(), x_data.max(), 100)
                    y_smooth = np.polyval(coeffs, x_smooth)
                    
                    plt.plot(x_smooth, y_smooth, color=color, linestyle='-', label=f'{curve_label} (R²={r_squared:.3f})')
                    
                    equation_str = format_polynomial_equation(coeffs, degree)
                    stats_list.append({
                        'curve': curve_label,
                        'equation': equation_str,
                        'r2': r_squared,
                        'rmse': rmse
                    })
                else:
                    plt.plot(x_data, y_data, marker='o', label=curve_label)
                
        plt.title('Зависимость ECL', fontsize=14)
        plt.xlabel(x_label, fontsize=12)
        plt.ylabel('ECL', fontsize=12)
        plt.legend(title=f"ЖК ({hue_label})", bbox_to_anchor=(1.05, 1), loc='upper left')
        plt.tight_layout()
        
        if do_regression and stats_list:
            show_stats_window(stats_list, degree)
        plt.show()

    # --- ТЕПЛОВАЯ КАРТА ---
    elif plot_type == "Heatmap":
        # Для тепловой карты можно выбрать только одну ЖК, иначе сетка сломается
        if len(selected_compounds) > 1:
            messagebox.showwarning("Внимание", "Для построения тепловой карты выберите только одну ЖК в списке!")
            return
            
        plt.figure(figsize=(10, 6))
        comp = selected_compounds[0]
        pivot_df = filtered_df.pivot(index=hue_col, columns=x_col, values="ECL")
        custom_cmap = LinearSegmentedColormap.from_list("blue_to_red", ["blue", "red"])
        sns.heatmap(pivot_df, annot=True, fmt=".3f", cmap=custom_cmap, cbar_kws={'label': 'ECL'})
        
        plt.title(f'Тепловая карта значений ECL ({comp})', fontsize=14)
        plt.xlabel(x_label, fontsize=12)
        plt.ylabel(hue_label, fontsize=12)
        plt.gca().invert_yaxis()
        plt.tight_layout()
        plt.show()

