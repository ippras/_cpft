df = pd.DataFrame(data, columns=['T0', 'dT', 'FA', 'RRT'])

# Предварительная обработка: заменяем прочерки на NaN и удаляем их, конвертируем в числа
df['RRT'] = pd.to_numeric(df['RRT'], errors='coerce')
df = df.dropna(subset=['RRT'])

# --- НАСТРОЙКИ СЕТКИ ---
t0_fine = np.linspace(df['T0'].min(), df['T0'].max(), 100)
dt_fine = np.linspace(df['dT'].min(), df['dT'].max(), 100)
T0_mesh, DT_mesh = np.meshgrid(t0_fine, dt_fine)

# --- РАСЧЕТ ПОВЕРХНОСТЕЙ И ПЕРЕСЕЧЕНИЙ ---
acids = df['FA'].unique()
surfaces = {}
for fa in acids:
    sub = df[df['FA'] == fa]
    # Интерполируем поверхность для каждой ЖК
    z = griddata((sub['T0'], sub['dT']), sub['RRT'], (T0_mesh, DT_mesh), method='cubic')
    surfaces[fa] = z

intersections = [] # Список для хранения найденных линий пересечения

# Перебор всех пар ЖК для поиска пересечений
for i in range(len(acids)):
    for j in range(i + 1, len(acids)):
        fa1, fa2 = acids[i], acids[j]
        z_diff = surfaces[fa1] - surfaces[fa2]
        
        # Ищем контур, где разность RRT равна 0
        fig_t, ax_t = plt.subplots()
        try:
            contour = ax_t.contour(T0_mesh, DT_mesh, z_diff, levels=[0])
            paths = contour.get_paths()
            plt.close(fig_t)
            
            for path in paths:
                v = path.vertices
                # Находим высоту RRT в точках пересечения
                z_inter = griddata((df[df['FA']==fa1]['T0'], df[df['FA']==fa1]['dT']), 
                                   df[df['FA']==fa1]['RRT'], (v[:,0], v[:,1]), method='cubic')
                intersections.append({
                    'pair': f"{fa1} / {fa2}",
                    'coords': np.column_stack((v[:,0], v[:,1], z_inter))
                })
        except:
            plt.close(fig_t)

# Вывод таблицы пересечений в консоль
print("\nНАЙДЕННЫЕ ПЕРЕСЕЧЕНИЯ:")
if not intersections:
    print("Пересечений не обнаружено.")
else:
    for inter in intersections:
        print(f"\nПара: {inter['pair']}")
        temp_df = pd.DataFrame(inter['coords'], columns=['T0', 'dT', 'RRT'])
        print(temp_df.iloc[::10].to_string(index=False)) # Вывод каждой 10-й точки

# --- ВИЗУАЛИЗАЦИЯ ---
fig = plt.figure(figsize=(14, 9))
ax = fig.add_subplot(111, projection='3d')
plt.subplots_adjust(bottom=0.2)

colors = plt.cm.tab10(np.linspace(0, 1, len(acids)))
scatter_objects = []

# Рисуем поверхности и точки данных
for i, fa in enumerate(acids):
    ax.plot_surface(T0_mesh, DT_mesh, surfaces[fa], alpha=0.2, color=colors[i])
    sub = df[df['FA'] == fa]
    sc = ax.scatter(sub['T0'], sub['dT'], sub['RRT'], color=colors[i], s=30, edgecolors='k', label=fa)
    scatter_objects.append((sc, fa))

# Рисуем линии пересечения
inter_scatters = []
for inter in intersections:
    pts = inter['coords']
    ax.plot(pts[:,0], pts[:,1], pts[:,2], color='red', linewidth=4, zorder=50)
    # Добавляем невидимые точки для работы подсказок на линии пересечения
    sc_i = ax.scatter(pts[::5,0], pts[::5,1], pts[::5,2], color='red', s=40, edgecolors='white')
    inter_scatters.append((sc_i, f"Пересечение {inter['pair']}"))

# --- ПОДСКАЗКИ (Figure Pixels) ---
annot = ax.annotate("", xy=(0,0), xytext=(15, 15), textcoords="offset points",
                    bbox=dict(boxstyle="round", fc="white", ec="gray", alpha=0.9),
                    arrowprops=dict(arrowstyle="->", color='gray'),
                    xycoords='figure pixels')
annot.set_visible(False)

def hover(event):
    if event.inaxes == ax:
        # Проверяем точки ЖК и точки пересечений
        for sc, label in scatter_objects + inter_scatters:
            cont, ind = sc.contains(event)
            if cont:
                pos = sc._offsets3d
                idx = ind["ind"][0]
                x, y, z = pos[0][idx], pos[1][idx], pos[2][idx]
                annot.set_text(f"Объект: {label}\nT0: {x:.2f}\ndT: {y:.2f}\RnRT: {z:.4f}")
                annot.xy = (event.x, event.y)
                annot.set_visible(True)
                fig.canvas.draw_idle()
                return
    if annot.get_visible():
        annot.set_visible(False)
        fig.canvas.draw_idle()

fig.canvas.mpl_connect("motion_notify_event", hover)

