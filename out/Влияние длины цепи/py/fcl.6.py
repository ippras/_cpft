acids = df['FA'].unique()

surfaces = {fa: griddata((df[df['FA']==fa]['T0'], df[df['FA']==fa]['dT']), 
                         df[df['FA']==fa]['FCL'], (T0_mesh, DT_mesh), method='linear') for fa in acids}

settings = {
    'colors': {fa: 'blue' if i==0 else 'red' for i, fa in enumerate(acids)}, 
    'alpha': 0.3,
    'z_min': df['FCL'].min() - 0.1,
    'z_max': df['FCL'].max() + 0.1
}

def draw_plot():
    elev, azim = ax.elev, ax.azim
    ax.cla()
    for fa in acids:
        ax.plot_surface(T0_mesh, DT_mesh, surfaces[fa], alpha=settings['alpha'], color=settings['colors'][fa], edgecolor='none')
        sub = df[df['FA'] == fa]
        ax.scatter(sub['T0'], sub['dT'], sub['FCL'], color=settings['colors'][fa], s=50, edgecolors='k')
    
    if len(acids) == 2:
        z_diff = surfaces[acids[0]] - surfaces[acids[1]]
        cs = ax.contour(T0_mesh, DT_mesh, z_diff, levels=[0], colors='black', linewidths=3)
        for path in cs.allsegs[0]:
            z_line = griddata((T0_mesh.flatten(), DT_mesh.flatten()), surfaces[acids[0]].flatten(), (path[:,0], path[:,1]))
            ax.plot(path[:,0], path[:,1], z_line, color='black', linewidth=3, zorder=100)

    ax.set_xlabel('T0'); ax.set_ylabel('dT'); ax.set_zlabel('FCL')
    ax.set_zlim(settings['z_min'], settings['z_max'])
    ax.view_init(elev=elev, azim=azim)
    fig.canvas.draw_idle()

