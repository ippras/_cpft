dt_fine = np.linspace(df['dT'].min(), df['dT'].max(), 100)
T0_mesh, DT_mesh = np.meshgrid(t0_fine, dt_fine)

# --- РАСЧЕТ ПОВЕРХНОСТЕЙ И ПЕРЕСЕЧЕНИЙ ---
acids = df['FA'].unique()
surfaces = {}
for fa in acids:
    sub = df[df['FA'] == fa]
    # Интерполируем поверхность для каждой ЖК
    z = griddata((sub['T0'], sub['dT']), sub['FCL'], (T0_mesh, DT_mesh), method='cubic')
    surfaces[fa] = z

intersections = [] # Список для хранения найденных линий пересечения

# Перебор всех пар ЖК для поиска пересечений
for i in range(len(acids)):
    for j in range(i + 1, len(acids)):
        fa1, fa2 = acids[i], acids[j]
        z_diff = surfaces[fa1] - surfaces[fa2]
        
        # Ищем контур, где разность FCL равна 0
        fig_t, ax_t = plt.subplots()
        try:
            contour = ax_t.contour(T0_mesh, DT_mesh, z_diff, levels=[0])
            paths = contour.get_paths()
            plt.close(fig_t)
            
            for path in paths:
                v = path.vertices
                # Находим высоту FCL в точках пересечения
                z_inter = griddata((df[df['FA']==fa1]['T0'], df[df['FA']==fa1]['dT']), 
                                   df[df['FA']==fa1]['FCL'], (v[:,0], v[:,1]), method='cubic')
                intersections.append({
                    'pair': f"{fa1} / {fa2}",
                    'coords': np.column_stack((v[:,0], v[:,1], z_inter))
                })
        except:
            plt.close(fig_t)

