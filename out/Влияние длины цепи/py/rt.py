def hover(event):
    if event.inaxes == ax:
        # Проверяем точки ЖК и точки пересечений
        for sc, label in scatter_objects + inter_scatters:
            cont, ind = sc.contains(event)
            if cont:
                pos = sc._offsets3d
                idx = ind["ind"][0]
                x, y, z = pos[0][idx], pos[1][idx], pos[2][idx]
                annot.set_text(f"Объект: {label}\nT0: {x:.2f}\ndT: {y:.2f}\RnRT: {z:.4f}")
                annot.xy = (event.x, event.y)
                annot.set_visible(True)
                fig.canvas.draw_idle()
                return
    if annot.get_visible():
        annot.set_visible(False)
        fig.canvas.draw_idle()

fig.canvas.mpl_connect("motion_notify_event", hover)

