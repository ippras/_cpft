df = df.dropna(subset=['FCL'])

class SettingsWindow:
    def __init__(self, root, update_callback):
        self.root = root
        self.root.title("Настройки визуализации")
        self.update_callback = update_callback
        
        tk.Label(root, text="Разрешение сетки (точек):").pack(pady=5)
        self.res_entry = tk.Entry(root)
        self.res_entry.insert(0, "100")
        self.res_entry.pack()
        
        tk.Button(root, text="Применить и перестроить", command=self.apply).pack(pady=20)

    def apply(self):
        try:
            res = int(self.res_entry.get())
            self.update_callback(res)
        except ValueError:
            messagebox.showerror("Ошибка", "Введите целое число")

def plot_data(resolution=100):
    plt.close('all')
    fig = plt.figure(figsize=(12, 8))
    ax = fig.add_subplot(111, projection='3d')
    
    t0_fine = np.linspace(df['T0'].min(), df['T0'].max(), resolution)
    dt_fine = np.linspace(df['dT'].min(), df['dT'].max(), resolution)
    T0_mesh, DT_mesh = np.meshgrid(t0_fine, dt_fine)
    
    acids = df['FA'].unique()
    surfaces = {}
    
    for fa in acids:
        sub = df[df['FA'] == fa]
        z = griddata((sub['T0'], sub['dT']), sub['FCL'], (T0_mesh, DT_mesh), method='cubic')
        surfaces[fa] = z
        ax.plot_surface(T0_mesh, DT_mesh, z, alpha=0.2)
        ax.scatter(sub['T0'], sub['dT'], sub['FCL'], label=fa)

    ax.set_xlabel('T0')
    ax.set_ylabel('dT')
    ax.set_zlabel('FCL')
    ax.legend()
    plt.show()

