# 2. Линейная регрессия для построения плоскостей
def get_plane_coeffs(sub_df):
    X = sub_df[['T0', 'dT']].values
    y = sub_df['ECL'].values
    model = LinearRegression().fit(X, y)
    # ECL = a*T0 + b*dT + c
    return model.coef_[0], model.coef_[1], model.intercept_

