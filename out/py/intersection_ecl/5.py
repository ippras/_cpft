def update_annot(sc, ind, label):
    # Получаем 3D координаты точки
    pos = sc._offsets3d
    idx = ind["ind"][0]
    x, y, z = pos[0][idx], pos[1][idx], pos[2][idx]
    
    # Текст подсказки
    text = f"{label}\nT0: {x:.2f}\ndT: {y:.2f}\nECL: {z:.4f}"
    annot.set_text(text)
    
    # Для 3D нужно проецировать координаты в 2D пиксели для корректного отображения аннотации
    # Но в Matplotlib проще привязать аннотацию к экранным координатам мыши
    annot.xy = (event_mouse.x, event_mouse.y)

def hover(event):
    global event_mouse
    event_mouse = event
    vis = annot.get_visible()
    if event.inaxes == ax:
        # Проверяем каждую группу точек
        for sc, label in [(sc1, "FA1"), (sc2, "FA2"), (sc_inter, "Intersection")]:
            cont, ind = sc.contains(event)
            if cont:
                update_annot(sc, ind, label)
                annot.set_visible(True)
                fig.canvas.draw_idle()
                return
    if vis:
        annot.set_visible(False)
        fig.canvas.draw_idle()

fig.canvas.mpl_connect("motion_notify_event", hover)

